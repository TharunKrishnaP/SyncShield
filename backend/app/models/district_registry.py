def build_districts():
    """Return the district registry as a list of dicts with stable ids."""
    out = []
    seen = set()
    for state, district, hq, lat, lon in DISTRICT_ROWS:
        code = STATE_CODES.get(state, "IN")
        key = f"{code}-{district}"
        if key in seen:
            continue
        seen.add(key)
        out.append({
            "id": key,
            "state": state,
            "state_code": code,
            "district": district,
            "hq": hq,
            "lat": round(lat, 4),
            "lon": round(lon, 4),
            "flood_prone": (state, district) in FLOOD_PRONE_DISTRICTS,
        })
    return out


DISTRICTS = build_districts()
DISTRICT_INDEX = {d["id"]: d for d in DISTRICTS}
